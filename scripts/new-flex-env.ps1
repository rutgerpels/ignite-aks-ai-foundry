# Generates the shared environment file used by the Microsoft Learn flex node walkthrough
# (plan-flex-nodes-deployment) pre-filled with this lab's resources and address plan.
# Output: .flex/ignite-flex.env  -> copy it into your Bash environment (WSL) at ~/.config/aks-flexnode/
$ErrorActionPreference = 'Stop'
function Get-AzdValue($name) { (azd env get-value $name).Trim() }

$root = Split-Path $PSScriptRoot -Parent
$rg = Get-AzdValue AZURE_RESOURCE_GROUP
$cluster = Get-AzdValue AKS_PLANT_NAME
$aksVersion = az aks show -g $rg -n $cluster --query currentKubernetesVersion -o tsv
$subnetId = az network vnet subnet show -g $rg --vnet-name vnet-cloud -n snet-aks-plant --query id -o tsv
$vmId = az vm show -g $rg -n (Get-AzdValue EDGE_VM_NAME) --query id -o tsv
$hostPrincipal = az identity show --ids (Get-AzdValue EDGE_VM_IDENTITY_ID) --query principalId -o tsv

$values = [ordered]@{
    SUBSCRIPTION_ID          = (az account show --query id -o tsv)
    LOCATION                 = (Get-AzdValue AZURE_LOCATION)
    RESOURCE_GROUP           = $rg
    CLUSTER_NAME             = $cluster
    FLEX_POOL_NAME           = 'plant2edge'
    AKS_API_ACCESS           = 'public'
    AKS_VNET_NAME            = 'vnet-cloud'
    AKS_VNET_RESOURCE_GROUP  = $rg
    AKS_SUBNET_NAME          = 'snet-aks-plant'
    AKS_SUBNET_ID            = $subnetId
    AKS_SUBNET_CIDR          = '10.10.8.0/24'
    AKS_NODE_CIDR            = '10.10.8.0/24'
    AKS_POD_CIDR             = '10.100.0.0/16'
    FLEX_HOST_SUBNET_CIDR    = '10.20.1.0/24'
    FLEX_NODE_CIDR           = '10.20.1.0/24'
    FLEX_POD_CIDR            = '10.101.0.0/16'
    SERVICE_CIDR             = '10.110.0.0/16'
    DNS_SERVICE_IP           = '10.110.0.10'
    AKS_NODE_VM_SIZE         = 'Standard_D2s_v5'
    AKS_VERSION              = $aksVersion
    AKS_PREVIEW_VERSION      = '22.0.0b8'
    UNBOUNDED_VERSION        = 'v0.8.0'
    AKS_FLEX_NODE_VERSION    = 'v0.2.0'
    AKS_RESOURCE_ID          = (Get-AzdValue AKS_PLANT_ID)
    FLEX_HOST_NAME           = (Get-AzdValue EDGE_VM_NAME)
    FLEX_HOST_SSH_TARGET     = "azureuser@$(Get-AzdValue EDGE_VM_PUBLIC_IP)"
    FLEX_HOST_PRIVATE_IP     = (Get-AzdValue EDGE_VM_PRIVATE_IP)
    HOST_PRINCIPAL_OBJECT_ID = $hostPrincipal
    HOST_IDENTITY_CLIENT_ID  = (Get-AzdValue EDGE_VM_IDENTITY_CLIENT_ID)
    SSH_PUBLIC_KEY_PATH      = '${HOME}/.ssh/ignite_lab.pub'
    SSH_PRIVATE_KEY_PATH     = '${HOME}/.ssh/ignite_lab'
    VM_RESOURCE_GROUP        = $rg
    VM_NAME                  = (Get-AzdValue EDGE_VM_NAME)
    VM_RESOURCE_ID           = $vmId
}

$helper = @'
set_flexnode_env() {
    if [[ "$#" -ne 2 || ! "$1" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
        printf 'Usage: set_flexnode_env NAME VALUE\n' >&2
        return 2
    fi
    local name="$1" value="$2" temporary_file
    temporary_file="$(mktemp "$(dirname "${FLEXNODE_ENV_FILE}")/flexnode.env.XXXXXX")" || return 1
    awk -v prefix="export ${name}=" 'index($0, prefix) != 1 { print }' "${FLEXNODE_ENV_FILE}" > "${temporary_file}" &&
        printf 'export %s=%q\n' "${name}" "${value}" >> "${temporary_file}" &&
        install -m 0600 "${temporary_file}" "${FLEXNODE_ENV_FILE}"
    local rc=$?
    rm -f "${temporary_file}"
    [[ $rc -eq 0 ]] && export "${name}=${value}"
}
'@

$lines = @($helper, '# Lab values (generated by scripts/new-flex-env.ps1)')
foreach ($k in $values.Keys) {
    $v = $values[$k]
    if ($v -like '${HOME}*') { $lines += "export $k=`"$v`"" } else { $lines += "export $k='$v'" }
}
$lines += 'export WORK_DIR="${HOME}/.local/share/aksflexnode/${FLEXNODE_DEPLOYMENT}"'
foreach ($k in 'FLEXNODE_KUBECONFIG', 'FLEX_POOL_RESOURCE_ID', 'FLEX_MACHINE_NAME', 'ARC_RESOURCE_GROUP', 'ARC_MACHINE_NAME', 'ARC_RESOURCE_ID', 'SP_TENANT_ID', 'SP_CLIENT_ID', 'SP_OBJECT_ID') {
    $lines += "export $k=''"
}

$outDir = Join-Path $root '.flex'
New-Item -ItemType Directory -Force $outDir | Out-Null
$out = Join-Path $outDir 'ignite-flex.env'
[IO.File]::WriteAllText($out, (($lines -join "`n") + "`n"))
Write-Host "Wrote $out (AKS_VERSION=$aksVersion)"
